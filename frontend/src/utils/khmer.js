export function translate(key, lang = 'km') {
  return translations[lang]?.[key] || translations['km']?.[key] || key;
}

const khmerNumerals = ['០','១','២','៣','៤','៥','៦','៧','៨','៩'];

export function formatKhmerNumber(num) {
  return String(num).replace(/\d/g, d => khmerNumerals[Number(d)]);
}

export function transliterateToKhmer(text) {
  if (!text || typeof text !== 'string') return text;
  const romanToKhmerMap = {
    'a':'អ','b':'ប','c':'ក','d':'ដ','e':'អែ','f':'ភ','g':'គ','h':'ហ',
    'i':'អី','j':'ច','k':'ខ','l':'ល','m':'ម','n':'ន','o':'អូ','p':'ភ',
    'q':'ក្ឌុង','r':'រ','s':'ស','t':'ត','u':'អុ','v':'វ','w':'វ',
    'x':'សខ','y':'យ','z':'ស'
  };
  return text.split('').map(ch => romanToKhmerMap[ch.toLowerCase()] || ch).join('');
}
